const files = fs.readdirSync(modulesDir).filter(f => f.endsWith('.js'));

files.forEach(file => {
  const filePath = path.join(modulesDir, file);
  let content = fs.readFileSync(filePath, 'utf8');

  Object.entries(breakdowns).forEach(([topicId, breakdown]) => {
    // If the file contains this topic ID and does not already have easyBreakdown for it
    const idRegex = new RegExp(`id:\\s*'${topicId}'[\\s\\S]*?content:\\s*\\{`);
    if (idRegex.test(content) && !content.includes(`oneLiner: '${breakdown.oneLiner}'`)) {
      const easyBreakdownStr = `
        easyBreakdown: {
          oneLiner: '${breakdown.oneLiner.replace(/'/g, "\\'")}',
          analogy: '${breakdown.analogy.replace(/'/g, "\\'")}',
          whyNeed: '${breakdown.whyNeed.replace(/'/g, "\\'")}'
        },`;

      content = content.replace(
        idRegex,
        (match) => `${match}${easyBreakdownStr}`
      );
      console.log(`Injected easyBreakdown into topic: ${topicId}`);
    }
  });

  fs.writeFileSync(filePath, content, 'utf8');
});

